"""Create the Android and iOS projects and apply the settings this app needs.

The android/ and ios/ folders are generated by Flutter and are not hand-written
in this repo. Run once, from app/, with Flutter on your PATH:

    python tool/setup_platforms.py [org]        # e.g. com.yourcompany.sttdemo

It runs `flutter create` (which keeps the existing lib/ and pubspec.yaml) and
then patches:
  Android: RECORD_AUDIO + INTERNET permissions, cleartext HTTP (the dev proxy
           is plain http on your LAN), minSdk 24.
  iOS:     microphone usage text, local-network HTTP exception, iOS 15 target.

Safe to run again: each patch is applied only if it is missing.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
ORG = sys.argv[1] if len(sys.argv) > 1 else "com.example.sttdemo"  # reverse-domain app id prefix


def patch(path: Path, describe: str, apply) -> None:
    if not path.exists():
        print(f"  skipped (not found): {path.relative_to(APP)}")
        return
    before = path.read_text(encoding="utf-8")
    after = apply(before)
    if after != before:
        path.write_text(after, encoding="utf-8", newline="\n")
        print(f"  patched {path.relative_to(APP)}: {describe}")
    else:
        print(f"  ok      {path.relative_to(APP)}: {describe}")


def android_manifest(text: str) -> str:
    for permission in ("RECORD_AUDIO", "INTERNET"):
        line = f'<uses-permission android:name="android.permission.{permission}"/>'
        if f"android.permission.{permission}" not in text:
            text = re.sub(r"(<manifest[^>]*>)", r"\1\n    " + line, text, count=1)
    if "usesCleartextTraffic" not in text:
        text = text.replace("<application", '<application\n        android:usesCleartextTraffic="true"', 1)
    return text


def android_gradle(text: str) -> str:
    # Flutter's default minSdk already satisfies the plugins (record: 23,
    # sherpa_onnx: 21); pin it explicitly so it does not drift lower.
    return re.sub(r"minSdk\s*=\s*flutter\.minSdkVersion", "minSdk = 24", text)


def ios_plist(text: str) -> str:
    additions = ""
    if "NSMicrophoneUsageDescription" not in text:
        additions += (
            "\t<key>NSMicrophoneUsageDescription</key>\n"
            "\t<string>The microphone is used to record speech for transcription tests.</string>\n"
        )
    if "NSAppTransportSecurity" not in text:
        additions += (
            "\t<key>NSAppTransportSecurity</key>\n"
            "\t<dict>\n"
            "\t\t<key>NSAllowsLocalNetworking</key>\n"
            "\t\t<true/>\n"
            "\t\t<key>NSAllowsArbitraryLoads</key>\n"
            "\t\t<true/>\n"
            "\t</dict>\n"
        )
    if "NSLocalNetworkUsageDescription" not in text:
        additions += (
            "\t<key>NSLocalNetworkUsageDescription</key>\n"
            "\t<string>Connects to the STT proxy running on your computer.</string>\n"
        )
    if additions:
        head, sep, tail = text.rpartition("</dict>")
        text = head + additions + sep + tail
    return text


def ios_podfile(text: str) -> str:
    return re.sub(r"^#?\s*platform :ios, '[^']+'", "platform :ios, '15.0'", text, count=1, flags=re.M)


def main() -> int:
    flutter = shutil.which("flutter")
    if flutter is None:
        print("flutter was not found on PATH. Install Flutter (https://docs.flutter.dev/get-started/install) first.")
        return 1
    print("running flutter create (keeps lib/ and pubspec.yaml)")
    subprocess.run(
        [flutter, "create", "--project-name", "stt_demo", "--org", ORG, "--platforms", "android,ios", "."],
        cwd=APP, check=True,
    )
    # flutter create adds a counter-app widget test that does not match this app.
    default_test = APP / "test" / "widget_test.dart"
    if default_test.exists():
        default_test.unlink()

    print("applying platform settings")
    patch(APP / "android/app/src/main/AndroidManifest.xml", "permissions + cleartext HTTP", android_manifest)
    for name in ("build.gradle.kts", "build.gradle"):
        patch(APP / "android/app" / name, "minSdk 24", android_gradle)
    patch(APP / "ios/Runner/Info.plist", "microphone + local network", ios_plist)
    patch(APP / "ios/Podfile", "iOS 15 deployment target", ios_podfile)
    print("\nNext:  flutter pub get  &&  flutter test  &&  flutter run")
    print("Note: the cleartext/arbitrary-loads exceptions are for the local dev proxy; remove them for a real release.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
